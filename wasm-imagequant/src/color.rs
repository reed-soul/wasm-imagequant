impl RGBA {
    #[inline(always)]
    pub const fn new(r: u8, g: u8, b: u8, a: u8) -> Self {
        Self { r, g, b, a }
    }

    /// 将 sRGB 单通道 [0, 255] 转换到线性光空间 [0.0, 1.0]
    #[inline(always)]
    pub fn srgb_to_linear(c: f32) -> f32 {
        if c <= 0.04045 {
            c / 12.92
        } else {
            ((c + 0.055) / 1.055).powf(2.4)
        }
    }

    /// 将线性光空间 [0.0, 1.0] 转换回 sRGB 单通道 [0.0, 1.0]
    #[inline(always)]
    pub fn linear_to_srgb(c: f32) -> f32 {
        if c <= 0.0031308 {
            c * 12.92
        } else {
            1.055 * c.powf(1.0 / 2.4) - 0.055
        }
    }

    /// 转换为 Oklab 空间表示 (零开销查表 + 极致向量化)
    #[inline(always)]
    pub fn to_oklab(&self) -> ColorOklab {
        let alpha = self.a as f32 * (1.0 / 255.0);
        if alpha <= 0.001 {
            return ColorOklab {
                l: 0.0,
                a: 0.0,
                b: 0.0,
                alpha: 0.0,
            };
        }

        let r_lin = SRGB_TO_LINEAR_LUT[self.r as usize];
        let g_lin = SRGB_TO_LINEAR_LUT[self.g as usize];
        let b_lin = SRGB_TO_LINEAR_LUT[self.b as usize];

        let l = 0.4122214708 * r_lin + 0.5363325363 * g_lin + 0.0514459929 * b_lin;
        let m = 0.2119034982 * r_lin + 0.6806995451 * g_lin + 0.1073969566 * b_lin;
        let s = 0.0883024619 * r_lin + 0.2817188376 * g_lin + 0.6299787005 * b_lin;

        let l_ = l.cbrt();
        let m_ = m.cbrt();
        let s_ = s.cbrt();

        ColorOklab {
            l: 0.2104542553 * l_ + 0.7936177850 * m_ - 0.0040720468 * s_,
            a: 1.9779984951 * l_ - 2.4285922050 * m_ + 0.4505937099 * s_,
            b: 0.0259040371 * l_ + 0.7827717662 * m_ - 0.8086757660 * s_,
            alpha,
        }
    }
}

/// Oklab 色彩空间结构
#[derive(Copy, Clone, Debug, Default, PartialEq)]
pub struct ColorOklab {
    /// 感知亮度 (Lightness)
    pub l: f32,
    /// 绿-红轴 (Green - Red)
    pub a: f32,
    /// 蓝-黄轴 (Blue - Yellow)
    pub b: f32,
    /// 不透明度 (Alpha, 0.0 - 1.0)
    pub alpha: f32,
}

impl ColorOklab {
    #[inline(always)]
    pub fn new(l: f32, a: f32, b: f32, alpha: f32) -> Self {
        Self { l, a, b, alpha }
    }

    /// 转回 RGBA 空间
    pub fn to_rgba(&self) -> RGBA {
        if self.alpha <= 0.001 {
            return RGBA::new(0, 0, 0, 0);
        }

        let l_ = self.l + 0.3963377774 * self.a + 0.2158037573 * self.b;
        let m_ = self.l - 0.1055613458 * self.a - 0.0638541728 * self.b;
        let s_ = self.l - 0.0894841775 * self.a - 1.2914855480 * self.b;

        let l = l_ * l_ * l_;
        let m = m_ * m_ * m_;
        let s = s_ * s_ * s_;

        let r_lin = 4.0767416621 * l - 3.3077115913 * m + 0.2309699292 * s;
        let g_lin = -1.2684380046 * l + 2.6097574011 * m - 0.3413193965 * s;
        let b_lin = -0.0041960863 * l - 0.7034186147 * m + 1.7076147010 * s;

        let r = (RGBA::linear_to_srgb(r_lin.clamp(0.0, 1.0)) * 255.0).round() as u8;
        let g = (RGBA::linear_to_srgb(g_lin.clamp(0.0, 1.0)) * 255.0).round() as u8;
        let b = (RGBA::linear_to_srgb(b_lin.clamp(0.0, 1.0)) * 255.0).round() as u8;
        let a = (self.alpha.clamp(0.0, 1.0) * 255.0).round() as u8;

        RGBA::new(r, g, b, a)
    }

    /// 计算在人眼感知下的色差平方 (Perceptual Distance Squared)
    ///
    /// 结合了 Oklab 距离与透明通道权重，平滑处理半透明渐变
    #[inline(always)]
    pub fn perceptual_distance_sq(&self, other: &Self) -> f32 {
        let avg_alpha = (self.alpha + other.alpha) * 0.5;
        if avg_alpha < 0.001 {
            return 0.0;
        }

        let d_alpha = self.alpha - other.alpha;
        let dl = self.l - other.l;
        let da = self.a - other.a;
        let db = self.b - other.b;

        // 色度差异随不透明度衰减，Alpha差异提供高权重约束
        (dl * dl + da * da + db * db) * avg_alpha + (d_alpha * d_alpha * 2.0)
    }
}
